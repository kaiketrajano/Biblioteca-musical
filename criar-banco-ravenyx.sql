-- Ravenyx | Criação do banco de dados para uma instalação nova.
-- No psql, execute o arquivo conectado primeiro ao banco postgres.
\set ON_ERROR_STOP on

CREATE DATABASE sistema_musical ENCODING 'UTF8';
\connect sistema_musical

SET client_encoding TO 'UTF8';
BEGIN;

-- Um artista pode ter vários álbuns.
CREATE TABLE public.artista (
    id_artista integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nome_artistico varchar(150) NOT NULL,
    biografia varchar(1000),
    data_criacao date,
    verificado boolean DEFAULT false
);

CREATE TABLE public.album (
    id_album integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nome varchar(150) NOT NULL,
    nota double precision,
    id_artista integer NOT NULL,
    imagem_url varchar(2048),
    spotify_id varchar(22),
    spotify_capa_url varchar(2048),
    CONSTRAINT fk_album_artista FOREIGN KEY (id_artista)
        REFERENCES public.artista (id_artista)
);

-- O formulário de músicas lê daqui as opções de gênero.
CREATE TABLE public.genero_musical (
    id_genero integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(80) NOT NULL UNIQUE CHECK (btrim(nome) <> '')
);

CREATE TABLE public.musica (
    id_musica integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo varchar(150) NOT NULL CHECK (btrim(titulo) <> ''),
    numero_faixa integer NOT NULL CHECK (numero_faixa > 0),
    duracao_segundos integer NOT NULL CHECK (duracao_segundos > 0),
    id_album integer NOT NULL,
    id_genero integer,
    imagem_url varchar(2048),
    spotify_single_id varchar(22),
    spotify_capa_url varchar(2048),

    -- A faixa precisa de um álbum, e o álbum só pode sair depois das faixas.
    CONSTRAINT musica_album_fk FOREIGN KEY (id_album)
        REFERENCES public.album (id_album) ON DELETE RESTRICT,
    CONSTRAINT musica_genero_fk FOREIGN KEY (id_genero)
        REFERENCES public.genero_musical (id_genero) ON DELETE RESTRICT,

    -- Álbuns diferentes podem ter uma faixa 1 cada.
    CONSTRAINT musica_album_faixa_un UNIQUE (id_album, numero_faixa)
);

INSERT INTO public.genero_musical (nome)
VALUES ('Rock'), ('Metal'), ('Pop'), ('Eletrônica'), ('Hip-hop'), ('MPB');

COMMIT;
